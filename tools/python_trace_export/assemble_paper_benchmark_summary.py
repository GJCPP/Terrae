#!/usr/bin/env python3
"""Assemble the machine-readable inputs for every paper benchmark table."""

from __future__ import annotations

import argparse
import csv
import json
import shutil
from pathlib import Path
from typing import Any


GBDT_FILES = ("summary.csv", "terrae_summary.csv", "zkboost_summary.csv", "soundness_summary.csv")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--scaling-dir", type=Path, required=True,
                        help="output directory of `make benchmark`")
    parser.add_argument("--practical-dir", type=Path, required=True,
                        help="output directory of `make benchmark-practical`")
    parser.add_argument("--histogram-dir", type=Path, required=True,
                        help="output directory of `make benchmark-histogram`")
    parser.add_argument("--output-dir", type=Path, required=True)
    return parser.parse_args()


def read_csv(path: Path) -> tuple[list[str], list[dict[str, str]]]:
    if not path.is_file():
        raise FileNotFoundError(f"missing benchmark summary: {path}")
    with path.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        fields = list(reader.fieldnames or [])
        if not fields:
            raise ValueError(f"missing CSV header: {path}")
        return fields, list(reader)


def merge_gbdt_file(name: str, scaling_dir: Path, practical_dir: Path, output_dir: Path) -> int:
    scaling_fields, scaling_rows = read_csv(scaling_dir / name)
    practical_fields, practical_rows = read_csv(practical_dir / name)
    fields = list(scaling_fields)
    fields.extend(field for field in practical_fields if field not in fields)
    output_path = output_dir / name
    with output_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(scaling_rows)
        writer.writerows(practical_rows)
    return len(scaling_rows) + len(practical_rows)


def copy_histogram(histogram_dir: Path, output_dir: Path) -> int:
    source = histogram_dir / "summary.csv"
    fields, rows = read_csv(source)
    shutil.copy2(source, output_dir / "histogram_summary.csv")
    summary_md = histogram_dir / "summary.md"
    if summary_md.is_file():
        shutil.copy2(summary_md, output_dir / "histogram_summary.md")
    return len(rows)


def main() -> int:
    args = parse_args()
    output_dir = args.output_dir
    output_dir.mkdir(parents=True, exist_ok=True)

    row_counts = {
        name: merge_gbdt_file(name, args.scaling_dir, args.practical_dir, output_dir)
        for name in GBDT_FILES
    }
    row_counts["histogram_summary.csv"] = copy_histogram(args.histogram_dir, output_dir)

    manifest: dict[str, Any] = {
        "scaling_dir": str(args.scaling_dir),
        "practical_dir": str(args.practical_dir),
        "histogram_dir": str(args.histogram_dir),
        "files": {
            "summary.csv": "all cross-system GBDT rows",
            "terrae_summary.csv": "Terrae-native GBDT metrics",
            "zkboost_summary.csv": "CertXGB-native GBDT metrics",
            "soundness_summary.csv": "Appendix K soundness ledgers for Terrae proofs",
            "histogram_summary.csv": "histogram microbenchmark rows",
        },
        "row_counts": row_counts,
    }
    (output_dir / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (output_dir / "README.md").write_text(
        "# Paper benchmark summaries\n\n"
        "Generated by `make benchmark-paper-summary`.  The four GBDT CSV files "
        "combine the scaling and practical benchmark outputs; `histogram_summary.csv` "
        "contains the histogram microbenchmark.  `manifest.json` records the source "
        "directories and row counts.\n",
        encoding="utf-8",
    )
    print(f"Paper benchmark summaries: {output_dir}")
    for name, count in row_counts.items():
        print(f"  {name}: {count} rows")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
